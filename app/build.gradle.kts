android {
    namespace = "com.example.notebook"
    compileSdk {
        version = release(37)
    }

    defaultConfig {
        applicationId = "com.example.notebook"
        minSdk = 24
        targetSdk = 37
        versionCode = 1
        versionName = "1.0"

        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
    }

    // Release signing key, read from keystore.properties (not in git; see docs/INSTALL.md).
    // Without that file the release build is simply unsigned and cannot be installed.
    val keystoreProperties = Properties().apply {
        val file = rootProject.file("keystore.properties")
        if (file.exists()) file.inputStream().use(::load)
    }
    signingConfigs {
        if (keystoreProperties.isNotEmpty()) {
            create("release") {
                storeFile = rootProject.file(keystoreProperties.getProperty("storeFile"))
                storePassword = keystoreProperties.getProperty("storePassword")
                keyAlias = keystoreProperties.getProperty("keyAlias")
                keyPassword = keystoreProperties.getProperty("keyPassword")
            }
        }
    }

    buildTypes {
        debug {
            // Debug builds install next to the real app ("Notebook Debug"), so testing
            // never touches the notes in the release version.
            applicationIdSuffix = ".debug"
        }
        release {
            optimization {
                enable = true
            }
            signingConfig = signingConfigs.findByName("release")
        }
    }
    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_11
        targetCompatibility = JavaVersion.VERSION_11
    }
    testOptions {
        // Robolectric needs Android resources to run Room tests on the JVM.
        unitTests.isIncludeAndroidResources = true
    }
    buildFeatures {
        compose = true
    }
}

